using System.Globalization;

namespace QuizFuzz.Client.Localization;

public static class AppStrings
{
    private static bool IsRussian => CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.Equals("ru", StringComparison.OrdinalIgnoreCase);

    public static string T(string key)
    {
        var source = IsRussian ? Ru : En;
        return source.TryGetValue(key, out var value) ? value : key;
    }

    public static string Tf(string key, params object?[] args) => string.Format(CultureInfo.CurrentUICulture, T(key), args);

    public static string Status(string status) => status switch
    {
        "Lobby" => T("RoomStatusLobby"),
        "InProgress" => T("RoomStatusInProgress"),
        "Finished" => T("RoomStatusFinished"),
        _ => status
    };

    public static string Difficulty(string difficulty) => difficulty switch
    {
        "Easy" => T("DifficultyEasy"),
        "Medium" => T("DifficultyMedium"),
        "Hard" => T("DifficultyHard"),
        "Expert" => T("DifficultyExpert"),
        _ => difficulty
    };

    public static string QuestionType(string? type) => Normalize(type) switch
    {
        "text" => T("QuestionTypeText"),
        "image" => T("QuestionTypeImage"),
        "audio" => T("QuestionTypeAudio"),
        "video" => T("QuestionTypeVideo"),
        _ => string.IsNullOrWhiteSpace(type) ? T("Unknown") : type!
    };

    public static string QuestionStatus(string? status) => Normalize(status) switch
    {
        "draft" => T("StatusDraft"),
        "underreview" or "under_review" or "pending" => T("StatusUnderReview"),
        "approved" => T("StatusApproved"),
        "rejected" => T("StatusRejected"),
        _ => string.IsNullOrWhiteSpace(status) ? T("Unknown") : status!
    };

    public static string QuestionDifficulty(string? difficulty) => Difficulty(NormalizeDifficulty(difficulty));

    public static string Role(string? role) => Normalize(role) switch
    {
        "admin" => T("RoleAdmin"),
        "moderator" => T("RoleModerator"),
        "user" => T("RoleUser"),
        _ => string.IsNullOrWhiteSpace(role) ? T("Unknown") : role!
    };

    public static string AnswerLabel(int number) => Tf("AnswerNumber", number);

    private static string Normalize(string? value) => (value ?? string.Empty).Replace("_", string.Empty).Trim().ToLowerInvariant();

    private static string NormalizeDifficulty(string? difficulty) => Normalize(difficulty) switch
    {
        "easy" => "Easy",
        "medium" => "Medium",
        "hard" => "Hard",
        "expert" => "Expert",
        _ => difficulty ?? string.Empty
    };

    public static string ModerationStatus(string status) => status switch
    {
        "Pending" => T("ModerationStatusPending"),
        "Approved" => T("ModerationStatusApproved"),
        "Rejected" => T("ModerationStatusRejected"),
        _ => status
    };

    public static string VictoryCondition(string type, int value) => type switch
    {
        "Points" => Tf("VictoryPoints", value),
        "Rounds" => Tf("VictoryRounds", value),
        _ => $"{type}: {value}"
    };

    public static string RelativeTime(DateTime createdAt)
    {
        var timeSpan = DateTime.UtcNow - createdAt;
        if (timeSpan.TotalMinutes < 1) return T("JustNow");
        if (timeSpan.TotalMinutes < 60) return IsRussian
            ? FormatRussianAgo((int)timeSpan.TotalMinutes, "минуту", "минуты", "минут")
            : FormatEnglishAgo((int)timeSpan.TotalMinutes, "minute");
        if (timeSpan.TotalHours < 24) return IsRussian
            ? FormatRussianAgo((int)timeSpan.TotalHours, "час", "часа", "часов")
            : FormatEnglishAgo((int)timeSpan.TotalHours, "hour");
        return IsRussian
            ? FormatRussianAgo((int)timeSpan.TotalDays, "день", "дня", "дней")
            : FormatEnglishAgo((int)timeSpan.TotalDays, "day");
    }

    private static string FormatRussianAgo(int value, string one, string few, string many)
    {
        var mod10 = value % 10;
        var mod100 = value % 100;
        var word = mod10 == 1 && mod100 != 11
            ? one
            : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)
                ? few
                : many;

        return $"{value} {word} назад";
    }

    private static string FormatEnglishAgo(int value, string word)
        => value == 1 ? $"1 {word} ago" : $"{value} {word}s ago";

